/**
 * Finish a browser OAuth sign-in by consuming the one-time HttpOnly hand-over cookie set by the
 * callback. Resolves to the session user (with token), or null when no sign-in is pending.
 */
export const completeOAuthSignIn = async () => {
	const res = await fetch(`${WEBUI_API_BASE_URL}/auths/oauth/handoff`, {
		method: 'POST',
		headers: {
			'Content-Type': 'application/json'
		},
		credentials: 'include'
	});
	if (res.status === 404) {
		return null;
	}
	const data = await res.json().catch(() => null);
	if (!res.ok) {
		throw data?.detail ?? 'Sign-in could not be completed. Please try again.';
	}
	return data;
};

/**
 * Renew a first-party session. The HttpOnly refresh cookie travels with `credentials: 'include'`;
 * the Bearer header names the access token being renewed. Never throws on HTTP errors.
 */
export const refreshSessionToken = async (token: string) => {
	const res = await fetch(`${WEBUI_API_BASE_URL}/auths/refresh`, {
		method: 'POST',
		headers: {
			'Content-Type': 'application/json',
			Authorization: `Bearer ${token}`
		},
		credentials: 'include'
	});
	const data = await res.json().catch(() => null);
	const retryAfter = Number(res.headers.get('Retry-After'));
	return {
		status: res.status,
		data,
		retryAfter: Number.isFinite(retryAfter) && retryAfter > 0 ? retryAfter : null
	};
};

// Sign-out names the token it ends, so the server revokes that login's whole renewable lineage
// (even after expiry) instead of whatever the shared cookie currently holds. Throws when the server
// did not confirm, including network failures, so callers never report an unconfirmed sign-out.
export const userSignOut = async (token: string | null = localStorage.token ?? null) => {
	let error = null;

	const res = await fetch(`${WEBUI_API_BASE_URL}/auths/signout`, {
		method: 'POST',
		headers: {
			'Content-Type': 'application/json',
			...(token ? { Authorization: `Bearer ${token}` } : {})
		},
		credentials: 'include'
	})
		.then(async (res) => {
			if (!res.ok) throw await res.json();
			return res.json();
		})
		.catch((err) => {
			console.error(err);
			error = err?.detail ?? 'Sign out could not be confirmed. Please check your connection and try again.';
			return null;
		});

	if (error) {
		throw error;
	}

	sessionStorage.clear();
	return res;
};

export const getLogoutRedirectUrl = (redirectUrl?: string | null) => {
	const logoutUrl = new URL('/auth?state=logout', window.location.origin);
	const postLogoutUrl = new URL('/auth', window.location.origin);
	if (!redirectUrl) {
		return logoutUrl.href;
	}

	const url = new URL(redirectUrl, window.location.origin);
	if (url.origin === window.location.origin && url.pathname === '/auth') {
		url.searchParams.set('state', 'logout');
		return url.href;
	}

	const postLogoutRedirectUri = url.searchParams.get('post_logout_redirect_uri');
	if (postLogoutRedirectUri) {
		const configuredPostLogoutUrl = new URL(postLogoutRedirectUri, window.location.origin);
		if (
			configuredPostLogoutUrl.origin === window.location.origin &&
			configuredPostLogoutUrl.pathname === '/auth'
		) {
			url.searchParams.set('state', 'logout');
		}
		return url.href;
	}

	url.searchParams.set('post_logout_redirect_uri', postLogoutUrl.href);
	url.searchParams.set('state', 'logout');
	return url.href;
};

